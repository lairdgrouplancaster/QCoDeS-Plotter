"""Shared host requirements for the plot-window feature mixins.

A mixin requires these methods; it does not supply a second implementation of
another feature's methods. Keep the declarations in one place so both typing
and method ownership follow that distinction. At runtime this is an empty,
cooperative base; the feature mixins and plotWidget provide the implementations.
"""

from typing import TYPE_CHECKING, Any

if TYPE_CHECKING:
    from PyQt6 import QtGui

    from ._commands import CommandSpec


class PlotHost:
    if TYPE_CHECKING:
        def show_status(self, message: str, timeout: int = 5000) -> None: ...
        def show_plot_state(
            self, title: object, detail: object | None = None, kind: str = "info",
        ) -> None: ...
        def hide_plot_state(self) -> None: ...
        def show_error(
            self, title: str, message: str, details: str | None = None,
        ) -> None: ...
        def register_shortcut(
            self, action: QtGui.QAction,
            shortcut: str | QtGui.QKeySequence | list[QtGui.QKeySequence]
                | tuple[QtGui.QKeySequence, ...] | CommandSpec,
            status_tip: str | None = None,
        ) -> None: ...
        @staticmethod
        def formatNum(num: float, sf: int = 3) -> str: ...
        def format_cursor_number(self, value: float) -> str: ...
        def _set_cursor_index_label(self, text: str) -> None: ...
        def _cursor_1d_x_data(self) -> Any: ...
        def apply_axis_major_tick_count_preference(self) -> None: ...
        def _update_plot_annotation(self) -> None: ...
        def _add_plot_overlay(self, item: Any, viewbox: Any = None) -> None: ...
        def _marquee_viewbox(self) -> Any: ...
        def _marquee_axis_assignment_changed(self) -> None: ...
        def _update_native_precision_status(self) -> None: ...
        def _heatmap_colorbar_items(self) -> list[Any]: ...
        def refreshWindow(self, force: bool = False) -> None: ...
        def clear_marquee(self) -> None: ...
